export const SIZE = 12;

// normalise to exactly 12×12 booleans, centred vertically on the filled rows
export const GLYPHS = Object.entries(RAW).map(([name, rows]) => {
    const grid = Array.from({ length: SIZE }, (_, r) => Array.from({ length: SIZE }, (_, c) => (rows[r] || "")[c] === "#"));
    const filled = grid.map((row) => row.some(Boolean));
    const top = filled.indexOf(true), bottom = filled.lastIndexOf(true);
    const shift = Math.floor((SIZE - 1 - bottom - top) / 2);
    const centred = Array.from({ length: SIZE }, (_, r) => grid[r - shift] ? grid[r - shift].slice() : new Array(SIZE).fill(false));
    return { name, grid: centred };
});
